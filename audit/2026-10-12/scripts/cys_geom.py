"""Build neutral (non-zwitterionic) L-cysteine, HSCH2-CH(NH2)-COOH, from standard internal coordinates.

Bond lengths (Angstrom) / angles (degrees) are generic textbook values, NOT an optimized structure.
They only provide documented, reproducible STARTING points that are then optimized at RHF/STO-3G.
Conformers are generated by varying chi1 (N-CA-CB-SG), chi2 (CA-CB-SG-HG) and the backbone
dihedral psi' (N-CA-C=O). Chirality is checked (L <=> (C-CA).((CB-CA)x(N-CA)) > 0, 'CORN' rule);
the RHF energy itself is identical for both enantiomers.
"""
import numpy as np


def place(a, b, c, bond, angle, dihedral):
    """NeRF: position of D given A, B, C with |CD| = bond, angle BCD, dihedral ABCD (degrees)."""
    a, b, c = map(np.asarray, (a, b, c))
    ang, dih = np.radians(angle), np.radians(dihedral)
    bc = c - b
    bc /= np.linalg.norm(bc)
    n = np.cross(b - a, bc)
    n /= np.linalg.norm(n)
    m = np.cross(n, bc)
    d2 = np.array([-bond * np.cos(ang), bond * np.sin(ang) * np.cos(dih), bond * np.sin(ang) * np.sin(dih)])
    return c + d2[0] * bc + d2[1] * m + d2[2] * n


def cysteine(chi1=-60.0, chi2=180.0, psi=160.0, chirality_sign=+1.0):
    X = {}
    X["N"] = np.array([0.0, 0.0, 0.0])
    X["CA"] = np.array([1.47, 0.0, 0.0])
    X["C"] = place([0, 1, 0], X["N"], X["CA"], 1.52, 110.0, 0.0)
    X["O1"] = place(X["N"], X["CA"], X["C"], 1.21, 124.0, psi)           # carbonyl O
    X["O2"] = place(X["N"], X["CA"], X["C"], 1.35, 112.0, psi + 180.0)   # hydroxyl O
    X["HO"] = place(X["CA"], X["C"], X["O2"], 0.97, 107.0, 180.0)        # syn COOH (O=C-O-H ~ 0)
    X["CB"] = place(X["C"], X["N"], X["CA"], 1.53, 110.5, chirality_sign * 122.0)
    X["HA"] = place(X["C"], X["N"], X["CA"], 1.09, 108.0, -chirality_sign * 118.0)
    X["H1"] = place(X["C"], X["CA"], X["N"], 1.01, 109.5, 60.0)
    X["H2"] = place(X["C"], X["CA"], X["N"], 1.01, 109.5, 180.0)
    X["SG"] = place(X["N"], X["CA"], X["CB"], 1.82, 114.0, chi1)
    X["HB1"] = place(X["N"], X["CA"], X["CB"], 1.09, 109.5, chi1 + 120.0)
    X["HB2"] = place(X["N"], X["CA"], X["CB"], 1.09, 109.5, chi1 - 120.0)
    X["HG"] = place(X["CA"], X["CB"], X["SG"], 1.34, 96.0, chi2)
    order = ["N", "H1", "H2", "CA", "HA", "CB", "HB1", "HB2", "SG", "HG", "C", "O1", "O2", "HO"]
    sym = {"N": "N", "CA": "C", "CB": "C", "C": "C", "SG": "S", "O1": "O", "O2": "O"}
    atoms = [(sym.get(k, "H"), X[k].tolist()) for k in order]
    return atoms


def chirality_triple(atoms):
    """(C-CA).((CB-CA)x(N-CA)) using the atom order of cysteine(); > 0 means L ('CORN' clockwise)."""
    P = [np.array(xyz) for _, xyz in atoms]
    N, CA, CB, C = P[0], P[3], P[5], P[10]
    return float(np.dot(C - CA, np.cross(CB - CA, N - CA)))


def l_cysteine(chi1, chi2, psi):
    atoms = cysteine(chi1, chi2, psi, +1.0)
    if chirality_triple(atoms) < 0:
        atoms = cysteine(chi1, chi2, psi, -1.0)
    assert chirality_triple(atoms) > 0
    return atoms


def min_nonbonded_distance(atoms):
    P = np.array([xyz for _, xyz in atoms])
    D = np.linalg.norm(P[:, None] - P[None], axis=-1)
    np.fill_diagonal(D, np.inf)
    return float(D.min())
